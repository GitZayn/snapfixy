  var LANGS = ["en", "es", "de", "fr", "pt"];
  var HTML_LANG = { en: "en-GB", es: "es", de: "de", fr: "fr", pt: "pt" };
  var STORAGE_KEY = "snapfixy-lang";
  var DETECTED_KEY = "snapfixy-lang-detected";
  var COUNTRY_LANG = {
    ES: "es", MX: "es", AR: "es", CO: "es", PE: "es", CL: "es", VE: "es",
    EC: "es", GT: "es", CU: "es", BO: "es", DO: "es", HN: "es", PY: "es",
    SV: "es", NI: "es", CR: "es", PA: "es", UY: "es",
    DE: "de", AT: "de", CH: "de",
    FR: "fr", BE: "fr",
    PT: "pt", BR: "pt", AO: "pt", MZ: "pt"
  };

  function isValid(lang) { return LANGS.indexOf(lang) !== -1; }
  function storeGet(key) {
    try { return window.localStorage.getItem(key); } catch (e) { return null; }
  }
  function storeSet(key, value) {
    try { window.localStorage.setItem(key, value); } catch (e) { /* private mode etc. */ }
  }

  function translate(dict, key) {
    if (dict && dict[key] != null) return dict[key];
    if (DICT.en[key] != null) return DICT.en[key];
    return null;
  }

  function apply(lang) {
    if (!isValid(lang)) lang = "en";
    var dict = DICT[lang];
    document.documentElement.setAttribute("lang", HTML_LANG[lang] || lang);

    var sel = document.getElementById("lang-select");
    if (sel && sel.value !== lang) sel.value = lang;

    var i, els, value;
    els = document.querySelectorAll("[data-i18n]");
    for (i = 0; i < els.length; i++) {
      value = translate(dict, els[i].getAttribute("data-i18n"));
      if (value != null) els[i].textContent = value;
    }
    els = document.querySelectorAll("[data-i18n-html]");
    for (i = 0; i < els.length; i++) {
      value = translate(dict, els[i].getAttribute("data-i18n-html"));
      if (value != null) els[i].innerHTML = value;
    }
    els = document.querySelectorAll("[data-i18n-ph]");
    for (i = 0; i < els.length; i++) {
      value = translate(dict, els[i].getAttribute("data-i18n-ph"));
      if (value != null) els[i].setAttribute("placeholder", value);
    }

    var page = document.body ? document.body.getAttribute("data-i18n-page") : null;
    if (page) {
      var title = translate(dict, "meta." + page + ".title");
      if (title != null) document.title = title;
      var desc = translate(dict, "meta." + page + ".desc");
      if (desc != null) {
        var meta = document.querySelector('meta[name="description"]');
        if (meta) meta.setAttribute("content", desc);
      }
    }
  }

  function detectAndApply() {
    var cached = storeGet(DETECTED_KEY);
    if (isValid(cached)) { apply(cached); return; }

    apply("en"); // sensible default while the one-off lookup runs
    if (typeof window.fetch !== "function") return;

    var controller = null;
    var timer = null;
    if (typeof window.AbortController === "function") {
      controller = new window.AbortController();
      timer = window.setTimeout(function () { controller.abort(); }, 3000);
    }
    window.fetch("https://ipwho.is/", controller ? { signal: controller.signal } : {})
      .then(function (res) { return res.json(); })
      .then(function (data) {
        if (timer) window.clearTimeout(timer);
        var cc = data && data.country_code ? String(data.country_code).toUpperCase() : "";
        var lang = COUNTRY_LANG[cc] || "en";
        storeSet(DETECTED_KEY, lang);
        if (lang !== "en") apply(lang);
      })
      .catch(function () {
        if (timer) window.clearTimeout(timer);
        /* Lookup failed: stay on English, silently. */
      });
  }

  function init() {
    var sel = document.getElementById("lang-select");
    if (sel) {
      sel.addEventListener("change", function () {
        var lang = isValid(sel.value) ? sel.value : "en";
        storeSet(STORAGE_KEY, lang);
        apply(lang);
      });
    }
    var saved = storeGet(STORAGE_KEY);
    if (isValid(saved)) { apply(saved); return; }
    detectAndApply();
  }

  /* Exposed for testing and possible future use; not required by the site. */
  window.SnapFixyI18n = { dict: DICT, apply: apply, countries: COUNTRY_LANG };

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init);
  } else {
    init();
  }
